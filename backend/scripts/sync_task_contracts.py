"""Generate identical, versioned wire modules in domain consumers; --check is read-only."""

from __future__ import annotations

import argparse
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONSUMERS = (
    "shopping-assistant/apps/api/src/shopping/integrations/personal_ai/task_wire.py",
    "personal-finance/services/api/app/integrations/task_wire.py",
    "personal-travel-app/backend/src/personal_travel/clients/task_wire.py",
    "health-app/services/api/src/health_api/integrations/task_wire.py",
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--projects-root", type=Path, default=ROOT.parent)
    args = parser.parse_args()
    source = (
        ROOT / "backend/src/personal_ai/contracts/delegated_tasks.py"
    ).read_bytes()
    header = (
        "# Generated by personal-ai-system/backend/scripts/sync_task_contracts.py.\n"
        f"# Source SHA256: {sha256(source).hexdigest()}.\n"
        "# Do not edit.\n"
    )
    generated = header.encode() + source
    stale = []
    for relative in CONSUMERS:
        target = args.projects_root / relative
        if not target.is_file() or target.read_bytes() != generated:
            stale.append(relative)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(generated)
        control_source = (ROOT / "backend/src/personal_ai/contracts/task_control.py").read_bytes()
        control_header = (
            "# Generated by personal-ai-system/backend/scripts/sync_task_contracts.py.\n"
            f"# Source SHA256: {sha256(control_source).hexdigest()}.\n"
            "# Do not edit.\n"
        ).encode()
        control_output = control_header + control_source.replace(
            b"from .delegated_tasks import", b"from .task_wire import"
        )
        control_target = target.with_name("task_control.py")
        if not control_target.is_file() or control_target.read_bytes() != control_output:
            stale.append(str(control_target.relative_to(args.projects_root)))
            if not args.check:
                control_target.write_bytes(control_output)
    if args.check and stale:
        print("Stale shared task consumers: " + ", ".join(stale))
        return 1
    print("Shared task consumers " + ("verified" if args.check else "generated"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
